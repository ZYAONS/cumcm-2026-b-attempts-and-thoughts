"""update_paper_numbers2.py -- the tables whose exact text differed from the
first script's anchors (no ': ' before the ranges, trailing spaces)."""
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def edit(fname, pairs):
    p = os.path.join(HERE, fname)
    s = io.open(p, encoding="utf-8").read()
    for a, b in pairs:
        if a not in s:
            print("  !! MISSING: %s" % a[:58].replace("\n", " "))
            continue
        s = s.replace(a, b, 1)
        print("  ok : %s" % a[:58].replace("\n", " "))
    io.open(p, "w", encoding="utf-8").write(s)


