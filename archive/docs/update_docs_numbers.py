"""update_docs_numbers.py -- refresh the numbers in the two technical reports and
in the verification report after the re-run."""
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def edit(fname, pairs):
    p = os.path.join(HERE, fname)
    s = io.open(p, encoding="utf-8").read()
    hit = 0
    for a, b in pairs:
        if a not in s:
            print("  -- not found in %s: %s" % (fname, a[:50].replace("\n", " ")))
            continue
        s = s.replace(a, b, 1)
        hit += 1
    io.open(p, "w", encoding="utf-8").write(s)
    print("  %s : %d replacements" % (fname, hit))


