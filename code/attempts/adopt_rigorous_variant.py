# -*- coding: utf-8 -*-
"""adopt_rigorous_variant.py -- 把"域外贴边环"固化为严格变体 P4_RIGOROUS，
并把本轮结论写进尝试日志。

事实（3 池各 20 例，共 60 例）：
  基线 域内 r=1750 n=12 ：594.8 s/源，完成率 0.9987（1 例失败），站位 24.0，动作 473.6
  严格 域外 r=1900 n=8  ：608.5 s/源，完成率 1.0000（0 例失败），站位 20.7，动作 436.2
组合（域外环 + 砍掉外圈格点）失败：行程涨到 30 km，完成率反而回到 0.9988。
"""
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# ---- 1) make_data.py 加严格变体 -------------------------------------------
p = os.path.join(HERE, "make_data.py")
s = io.open(p, encoding="utf-8").read()
if "P4_RIGOROUS" not in s:
    anchor = "P3 = {"
    i = s.find(anchor)
    assert i > 0, "P3 锚点缺失"
    block = '''# 严格变体（可选，非默认）：把贴边环从域内 r=1750 移到域外 r=1900。
# 动机：贴边朝外辐射的定向源，只有采样点半径大于源半径时才可能收到信号；
#       r=1750 的环覆盖不到 r>1750 的源，这正是 8.4 节"半平面黑洞"残留的缺口。
# 环移到域外后该缺口闭合，且环上点数可从 12 减到 8（角向容差约 +-32 度）。
# 实测（3 池各 20 例，共 60 例）：完成率 0.9987 -> 1.0000（1 例失败 -> 0 例），
#       站位 24.0 -> 20.7，动作 473.6 -> 436.2，代价是时间 594.8 -> 608.5 s per source（+2.3%）。
# 因 1/60 与 0/60 的失败差在统计上不显著，默认仍用快速配置；
# 本变体用于第 10.3 节讨论"用 2.3% 的时间换掉理论缺口"。
P4_RIGOROUS = {"rim_ring_r": 1900.0, "rim_ring_n": 8}

'''
    s = s[:i] + block + s[i:]
    io.open(p, "w", encoding="utf-8").write(s)
    print("make_data.py: 已加入 P4_RIGOROUS")
else:
    print("make_data.py: P4_RIGOROUS 已存在")

# ---- 2) 尝试日志 ----------------------------------------------------------
lp = os.path.join(HERE, "..", "report", "ATTEMPTS_LOG.md")
t = io.open(lp, encoding="utf-8").read()
if "域外贴边环" not in t:
    t += """
### 9.7 架构层尝试：把贴边环移到域外（得到严格变体，未换默认）

**几何动机**：贴边朝外辐射的定向源，只有当采样点的半径大于源半径时才可能收到信号。
域内 r=1750 的环覆盖不到 r>1750 的源，这正是 8.4 节"半平面黑洞"残留的缺口，也是
此前 `survey_max_r<=1500`（砍掉 r=1645 那圈格点）会让完成率掉到 0.9924 的原因。
把环移到**域外** r=1900 后该缺口闭合，且角向容差变为 cos(delta)>=0.85（约 +-32 度），
环上点数可从 12 减到 8。

**实测（问题四混合场景，3 池各 20 例 = 60 例）**：

| 配置 | 时间 | 完成率 | 失败 | 站位 | 动作 | 行程 |
| --- | --- | --- | --- | --- | --- | --- |
| 基线 域内 r=1750 n=12 | 594.8 | 0.9987 | 1 | 24.0 | 473.6 | 23.9 km |
| **严格 域外 r=1900 n=8** | 608.5 | **1.0000** | **0** | **20.7** | **436.2** | 25.8 km |
| 域外 r=1900 n=12 | 598.7 | 0.9985 | 1 | 22.6 | -- | -- |
| 域外 r=1900 n=6 | 582.7 | 0.9938 | 5 | 18.7 | -- | -- |
| 域外 r=1850 n=8 | 574.5 | 0.9971 | 2 | 20.3 | -- | -- |

**组合拳失败**：域外环 + 砍掉外圈格点（想让两者互补）反而更差 ——
`域外1900/8 + survey_max_r<=1500` 行程涨到 30.0 km、时间 667.2 s、完成率回到 0.9988。
原因是认证扫描会改由更远的补测点完成。

**判定**：严格变体（域外 1900/8）在 60 例上零失败、少 3.3 个站位、少 37 次动作，
但贵 2.3%。1/60 与 0/60 的失败差在统计上不显著，故**不换默认配置**，
而是固化为 `P4_RIGOROUS`（`code/make_data.py`），供第 10.3 节讨论
"用 2.3% 的时间换掉理论缺口"这一取舍。
"""
    io.open(lp, "w", encoding="utf-8").write(t)
    print("ATTEMPTS_LOG.md: 已追加 9.7 节")
else:
    print("ATTEMPTS_LOG.md: 已存在")
