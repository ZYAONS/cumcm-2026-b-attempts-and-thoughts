def main():
    fixed = 0
    for fname, a, b, tag in EDIT:
        p = os.path.join(HERE, fname)
        s = io.open(p, encoding="utf-8").read()
        if a not in s:
            print("  !! 锚点未找到 [%s] in %s" % (tag, fname))
            print("     %s" % a[:90].replace("\n", " "))
            continue
        s = s.replace(a, b, 1)
        io.open(p, "w", encoding="utf-8").write(s)
        fixed += 1
        print("  ok [%s]" % tag)
    print("已更新 %d/%d 处" % (fixed, len(EDIT)))
    return 0 if fixed == len(EDIT) else 1


if __name__ == "__main__":
    sys.exit(main())
